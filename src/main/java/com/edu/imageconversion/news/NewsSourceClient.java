package com.edu.imageconversion.news;

import com.edu.imageconversion.dto.NewsArticleDTO;

import java.util.List;

/**
 * Единый контракт для клиента, обращающегося к API конкретного новостного сайта.
 * <p>
 * Каждая реализация инкапсулирует всё, что специфично для конкретного источника:
 * URL, формат параметров запроса, ключ API и структуру JSON-ответа, — и приводит
 * результат к единой модели {@link NewsArticleDTO}. Благодаря этому
 * {@code NewsService} умеет параллельно опрашивать произвольный набор источников,
 * ничего не зная про их внутреннее устройство.
 * <p>
 * Реализации регистрируются как Spring-бины и автоматически подхватываются
 * сервисом через {@code List<NewsSourceClient>} constructor injection — чтобы
 * добавить ещё один источник новостей, достаточно реализовать этот интерфейс
 * и пометить класс аннотацией {@code @Component}.
 */
public interface NewsSourceClient {

    /**
     * Человекочитаемое имя источника, используемое в ответе API и в логах
     * (например, "NewsAPI.org", "The Guardian").
     */
    String getSourceName();

    /**
     * Синхронно выполняет запрос к API источника и возвращает найденные новости.
     * Метод предполагается блокирующим (обычный HTTP-вызов) — распараллеливание
     * вызовов разных источников обеспечивает вызывающая сторона (NewsService),
     * выполняя эти вызовы в пуле потоков.
     *
     * @param query поисковый запрос/ключевые слова
     * @param limit максимальное количество новостей, которое имеет смысл запросить у источника
     * @return список новостей от источника (может быть пустым, но не null)
     * @throws NewsSourceException если источник недоступен, не настроен (нет API-ключа)
     *                              или вернул ответ, который не удалось разобрать
     */
    List<NewsArticleDTO> fetchArticles(String query, int limit) throws NewsSourceException;
}
